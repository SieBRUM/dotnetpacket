    [Fact]
    public void ParseDisplayGroups_ReadsEveryGroupWithRidAttributesAndName()
    {
        (var groups, uint total, uint status) =
            Samr.ParseDisplayGroups(Convert.FromHexString(DisplayGroupsResp));

        Assert.Equal(0u, status);
        Assert.Equal(12u, total);
        Assert.Equal(12, groups.Count);

        Assert.Equal(1u, groups[0].Index);
        Assert.Equal(512u, groups[0].Rid);
        Assert.Equal("Domain Admins", groups[0].AccountName);
        Assert.StartsWith("Designated administrators", groups[0].AdminComment);
        Assert.Equal(0x7u, groups[0].Attributes);

        Assert.Contains(groups, g => g.Rid == 519u && g.AccountName == "Enterprise Admins");
        Assert.Contains(groups, g => g.AccountName == "Domain Users");
    }
